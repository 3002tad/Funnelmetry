import {readFile,writeFile,mkdir} from 'node:fs/promises'
import {createHash} from 'node:crypto'
import postcss from 'postcss'
import selectorParser from 'postcss-selector-parser'

// These sources are copied byte-for-byte from the approved HTML prototypes.
// Only namespace selectors, variables and animation names; never tune geometry here.
const root=new URL('../src/ui-template/',import.meta.url)
const bundles={analyst:['styles.css','compare.css','funnel-chart.css','price-interest.css','data-health-preview.css','events-system.css','presentation.css','system-theme.css','ai-shortcut.css'],admin:['styles.css','system-theme.css','admin.css']}
const imports=new Set(),output=[],manifest={}
for(const [role,files] of Object.entries(bundles)){
 const owner=`.template-root[data-ui="${role}"]`
 for(const file of files){
  const raw=await readFile(new URL(`source/${role}/${file}`,root),'utf8')
  manifest[`${role}/${file}`]=createHash('sha256').update(raw).digest('hex')
  const ast=postcss.parse(raw)
  ast.walkAtRules('import',rule=>{imports.add(rule.toString());rule.remove()})
  const animations=new Set()
  ast.walkAtRules(/keyframes$/,rule=>{animations.add(rule.params);rule.params='tpl-'+rule.params})
  ast.walkRules(rule=>{
   if(rule.parent?.type==='atrule'&&/keyframes$/.test(rule.parent.name))return
   rule.selector=selectorParser(selectors=>selectors.each(selector=>{
    selector.walkClasses(node=>{if(node.value!=='dark')node.value='tpl-'+node.value})
    let base=false
    selector.walkPseudos(node=>{if(node.value===':root'){node.replaceWith(selectorParser.className({value:'TEMPLATE_OWNER'}));base=true}})
    selector.walkTags(node=>{if(node.value==='body'||node.value==='html'){node.replaceWith(selectorParser.className({value:'TEMPLATE_OWNER'}));base=true}})
    // Body/root theme selectors have to keep .dark above the React owner.
    let text=selector.toString().replace(/\.TEMPLATE_OWNER\.dark/g,`.dark ${owner}`).replace(/\.TEMPLATE_OWNER/g,owner)
    if(!base){if(text.startsWith('.dark '))text=text.replace('.dark ',`.dark ${owner} `);else if(/^\.tpl-(collapsed|menu-open)(?=[\s.])/.test(text))text=owner+text;else text=owner+' '+text}
    selector.replaceWith(selectorParser().astSync(text).first)
   })).processSync(rule.selector)
  })
  ast.walkDecls(decl=>{decl.prop=decl.prop.replace(/^--/,'--tpl-');decl.value=decl.value.replace(/var\(--/g,'var(--tpl-');if(/animation/.test(decl.prop))for(const name of animations)decl.value=decl.value.replace(new RegExp(`\\b${name}\\b`,'g'),'tpl-'+name)})
  output.push(`/* ${role}/${file} */\n${ast.toString()}`)
 }
}
await mkdir(new URL('generated/',root),{recursive:true})
await writeFile(new URL('generated/template.css',root),`/* GENERATED by scripts/build-template-css.mjs. Edit source prototypes, not this file. */\n${[...imports].join(';\n')};\n${output.join('\n')}`)
await writeFile(new URL('source-manifest.json',root),JSON.stringify(manifest,null,2)+'\n')
console.log(`[ui-template] compiled ${Object.keys(manifest).length} unmodified prototype CSS sources`)
